-- revoke_anon_execute_on_internal_functions
--
-- Logged-out callers (role anon, i.e. anyone holding the public VITE_API_KEY) could
-- execute 436 functions in schema public through /rest/v1/rpc, 396 of them SECURITY DEFINER.
-- That is how public.current_cron_token() leaked the scheduler secret (fixed in
-- 20261109000000), and how anyone could call e.g. ensure_standard_coa_accounts() to
-- rename any tenant's accounts. Grants came from the platform default (ALTER DEFAULT
-- PRIVILEGES ... GRANT ALL ON FUNCTIONS TO anon) plus the implicit EXECUTE TO PUBLIC.
--
-- anon keeps EXECUTE only on the 44 functions logged-out code paths need:
--   * RPCs called from code reachable from public routes (LazyRoute pages: guest/QR
--     ordering, online ordering + tracking, table booking, driver and CFD links,
--     ZATCA report verification, signup, auth, tenant subdomains) and the app shell,
--   * helpers referenced by RLS policies that apply to anon/public (a policy calling a
--     function the role cannot execute errors instead of filtering),
--   * helpers called by SECURITY INVOKER trigger functions.
-- Every other function loses anon (and PUBLIC) EXECUTE: 156 trigger functions,
-- 155 called only from logged-in pages or server functions, and 81 not called by
-- the app at all (internal helpers, cron, legacy). authenticated and service_role keep
-- exactly the access they had. Signatures that no longer exist are skipped, and the
-- keep list is granted explicitly, so re-running this is safe.
-- Analysis and the full list with reasons: docs/self-hosting/FUNCTION_ACCESS_REVIEW.md.

