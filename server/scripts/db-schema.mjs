#!/usr/bin/env node
/**
 * Regenerates the Drizzle schema used by /api/v1 modules from the live database:
 *
 *   npm --prefix server run db:schema
 *
 * Runs `drizzle-kit pull` for the tables listed in drizzle.config.ts, then keeps only what the
 * modules need: table and column definitions, indexes, uniques and checks. Foreign keys, RLS
 * policies and relations are dropped. They point at tables outside the list, and Postgres
 * enforces them anyway. The database (db/migrations) stays the source of truth; Drizzle never
 * runs migrations here.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, rmSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "src", "db", "generated");

execFileSync(join(root, "node_modules", ".bin", "drizzle-kit"), ["pull"], { cwd: root, stdio: "inherit", env: process.env });

for (const f of readdirSync(outDir)) {
  if (f.endsWith(".sql") || f === "meta" || f === "relations.ts") rmSync(join(outDir, f), { recursive: true, force: true });
}

const file = join(outDir, "schema.ts");
let s = readFileSync(file, "utf8");
// Drop foreignKey({...}).onDelete(...).onUpdate(...) entries and pgPolicy(...) entries.
s = s.replace(/\n\tforeignKey\(\{[\s\S]*?\}\)(?:\.on(?:Delete|Update)\("[a-z ]+"\))*,/g, "");
s = s.replace(/\n\tpgPolicy\([\s\S]*?\}\),(?=\n)/g, "");
// Remove now-unused imports.
s = s.replace(/import \{([^}]*)\} from "drizzle-orm\/pg-core"/, (_m, names) => {
  const keep = names
    .split(",")
    .map((n) => n.trim())
    .filter((n) => n && new RegExp(`\\b${n}\\(`).test(s.replace(/^import[^\n]*\n/m, "")));
  return `import { ${keep.join(", ")} } from "drizzle-orm/pg-core"`;
});
const header = `// GENERATED by server/scripts/db-schema.mjs from the live database. Do not edit by hand.\n// Tables: see TABLES in server/drizzle.config.ts.\n`;
writeFileSync(file, header + s.replace(/^\/\/ GENERATED[^\n]*\n(\/\/[^\n]*\n)?/, ""));
console.log("wrote", file);
